#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-or-later
# Writes the AUR files (PKGBUILD and .SRCINFO) for one StowLock release.
#   make-pkgbuild.sh <tag> <binary> <out-dir>
# Run from the repo root, after the release binary is built. Betas go to the
# stowlock-beta-bin package, full releases to stowlock-bin.
set -eu
TAG="$1"; BIN="$2"; OUT="$3"
VER="${TAG#v}"
# Arch versions can't contain "-": 0.1.0-beta.3 -> 0.1.0beta3 (sorts before 0.1.0).
PKGVER="$(printf '%s' "$VER" | sed -E 's/-(alpha|beta|rc)\.?/\1/; s/-/_/g')"
case "$VER" in
  *-*) PKG=stowlock-beta-bin ;;
  *)   PKG=stowlock-bin ;;
esac
REPO="Matt-B-007/StowLock"
URL="https://github.com/$REPO"
SHA_BIN="$(sha256sum "$BIN" | cut -d' ' -f1)"
SHA_SVG="$(sha256sum assets/stowlock.svg | cut -d' ' -f1)"
SHA_LIC="$(sha256sum LICENSE | cut -d' ' -f1)"
mkdir -p "$OUT"
cat > "$OUT/PKGBUILD" <<PKG
# Maintainer: Matt-B-007 <https://github.com/Matt-B-007>
# Generated by StowLock's release workflow; edit packaging/aur/make-pkgbuild.sh instead.
pkgname=$PKG
pkgver=$PKGVER
pkgrel=1
pkgdesc="Turn project zips into clean, tested GitHub repos and releases"
arch=('x86_64')
url="$URL"
license=('GPL-3.0-or-later')
depends=('git' 'github-cli' 'gcc-libs' 'glibc')
optdepends=('kdialog: KDE file dialogs' 'zenity: GNOME file dialogs')
provides=('stowlock')
conflicts=('stowlock' 'stowlock-bin' 'stowlock-beta-bin')
options=('!strip' '!debug')
source=("stowlock-$VER::$URL/releases/download/$TAG/stowlock-linux-x86_64"
        "stowlock-$VER.svg::https://raw.githubusercontent.com/$REPO/$TAG/assets/stowlock.svg"
        "LICENSE-$VER::https://raw.githubusercontent.com/$REPO/$TAG/LICENSE")
sha256sums=('$SHA_BIN'
            '$SHA_SVG'
            '$SHA_LIC')

package() {
  install -Dm755 "stowlock-$VER" "\$pkgdir/usr/bin/stowlock"
  install -Dm644 "stowlock-$VER.svg" "\$pkgdir/usr/share/icons/hicolor/scalable/apps/stowlock.svg"
  install -Dm644 "LICENSE-$VER" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  install -Dm644 /dev/stdin "\$pkgdir/usr/share/applications/stowlock.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=StowLock
Comment=Turn project zips into clean, tested GitHub repos
Exec=stowlock %f
Icon=stowlock
Terminal=false
Categories=Development;
MimeType=application/zip;
DESKTOP
}
PKG
cat > "$OUT/.SRCINFO" <<SRC
pkgbase = $PKG
	pkgdesc = Turn project zips into clean, tested GitHub repos and releases
	pkgver = $PKGVER
	pkgrel = 1
	url = $URL
	arch = x86_64
	license = GPL-3.0-or-later
	depends = git
	depends = github-cli
	depends = gcc-libs
	depends = glibc
	optdepends = kdialog: KDE file dialogs
	optdepends = zenity: GNOME file dialogs
	provides = stowlock
	conflicts = stowlock
	conflicts = stowlock-bin
	conflicts = stowlock-beta-bin
	options = !strip
	options = !debug
	source = stowlock-$VER::$URL/releases/download/$TAG/stowlock-linux-x86_64
	source = stowlock-$VER.svg::https://raw.githubusercontent.com/$REPO/$TAG/assets/stowlock.svg
	source = LICENSE-$VER::https://raw.githubusercontent.com/$REPO/$TAG/LICENSE
	sha256sums = $SHA_BIN
	sha256sums = $SHA_SVG
	sha256sums = $SHA_LIC

pkgname = $PKG
SRC
echo "$PKG"
